-- base64 解码表
local B64 = {}
do
    local A = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
    for i = 1, #A do B64[A:sub(i, i)] = i - 1 end
end

-- base64 -> 字节数组（避免依赖固件是否提供 string 扩展）
local function b64decode(s)
    local out, n = {}, 0
    local acc, accbits = 0, 0
    for i = 1, #s do
        local v = B64[s:sub(i, i)]
        if v then
            acc = acc * 64 + v
            accbits = accbits + 6
            if accbits >= 8 then
                accbits = accbits - 8
                n = n + 1
                out[n] = math.floor(acc / (2 ^ accbits)) % 256
            end
        end
    end
    return out
end

-- 解码结果缓存（字模只解一次）
local cache = {}

--- 取某字的位图：返回 rows[y][x] = 0/1
function M.glyph(ch)
    if cache[ch] then return cache[ch] end
    local b64 = M.GLYPHS[ch]
    if not b64 then return nil end
    local bytes = b64decode(b64)
    local rows = {}
    local k = 1
    for y = 1, M.SIZE do
        local val = bytes[k] * 65536 + bytes[k + 1] * 256 + bytes[k + 2]
        k = k + 3
        local row = {}
        for x = 1, M.SIZE do
            row[x] = (math.floor(val / (2 ^ (M.SIZE - x))) % 2)
        end
        rows[y] = row
    end
    cache[ch] = rows
    return rows
end

return M
